class DatasetPreparationError(ValueError):
    """Raised when an input archive cannot be converted safely and unambiguously."""


@dataclass(slots=True)
class SplitReport:
    source_images: int = 0
    source_annotations: int = 0
    retained_images: int = 0
    retained_boxes: int = 0
    clipped_boxes: int = 0
    invalid_boxes_skipped: int = 0
    crowd_boxes_skipped: int = 0
    duplicate_boxes_skipped: int = 0
    tiny_boxes_at_320: int = 0
    excluded_images: int = 0
    unreferenced_archive_images: int = 0
    retained_source_categories: Counter[str] = field(default_factory=Counter)
    excluded_annotations: Counter[str] = field(default_factory=Counter)

    def serializable(self) -> dict[str, Any]:
        values = asdict(self)
        values["retained_source_categories"] = dict(
            sorted(self.retained_source_categories.items())
        )
        values["excluded_annotations"] = dict(sorted(self.excluded_annotations.items()))
        return values


@dataclass(frozen=True, slots=True)
class PreparedImage:
    split: str
    archive_name: str
    file_name: str
    label_lines: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class PreparationResult:
    output: Path
    archive_sha256: str
    reports: Mapping[str, SplitReport]
    leakage: Mapping[str, Any]


