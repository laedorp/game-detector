"""Prepare the FORT-Cuh Roboflow COCO archive for one-class YOLO training.

The source archive combines several incompatible annotation vocabularies. This
converter deliberately produces one "player" class, drops part/identity labels,
clips boxes to image bounds, and never calls ZipFile.extractall. Output is
written through a temporary sibling directory and renamed into place only after
the complete dataset has been validated and copied.
"""

