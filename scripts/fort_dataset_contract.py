"""Build and verify exact one-class FORT dataset membership/content contracts."""

from __future__ import annotations

from hashlib import sha256
import json
from pathlib import Path
from typing import Any, Mapping, Sequence


# Every image suffix Ultralytics 8.4.116 may discover from a directory. The
# generated FORT copy currently contains JPG files, but verification must also
# reject an injected BMP/WebP/etc. rather than silently excluding it from the
# contract while Ultralytics includes it in training or evaluation.
IMAGE_SUFFIXES = frozenset(
    {
        ".avif",
        ".bmp",
        ".dng",
        ".heic",
        ".heif",
        ".jp2",
        ".jpeg",
        ".jpg",
        ".mpo",
        ".png",
        ".tif",
        ".tiff",
        ".webp",
    }
)
DEFAULT_SPLITS = ("train", "valid", "test")
GROUPED_DATASET_YAML = (
    "# Generated by scripts/prepare_fort_cuh_grouped.py\n"
    "train: images/train\n"
    "val: images/valid\n"
    "test: images/test\n"
    "names:\n  0: player\n"
)
GROUPED_LABELS = "player\n"


class DatasetContractError(ValueError):
    """Raised when dataset files differ from their pinned contract."""


def _sha256_file(path: Path) -> str:
    digest = sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _regular_files(directory: Path, suffixes: frozenset[str]) -> dict[str, Path]:
    if not directory.is_dir() or directory.is_symlink():
        raise DatasetContractError(f"dataset directory missing or unsafe: {directory}")
    files: dict[str, Path] = {}
    for path in sorted(directory.iterdir(), key=lambda item: item.name.casefold()):
        if path.suffix.casefold() not in suffixes or not path.is_file() or path.is_symlink():
            raise DatasetContractError(f"unexpected dataset split member: {path}")
        if path.name in files:
            raise DatasetContractError(f"duplicate dataset member name: {path.name}")
        files[path.name] = path
    return files


def _reject_uncontracted_runtime_members(root: Path) -> None:
    """Reject implicit caches or alternate paths a dataset loader might consume."""

    for kind in ("images", "labels"):
        container = root / kind
        if not container.is_dir() or container.is_symlink():
            raise DatasetContractError(f"dataset directory missing or unsafe: {container}")
        for member in sorted(container.iterdir(), key=lambda item: item.name.casefold()):
            if (
                member.name in DEFAULT_SPLITS
                and member.is_dir()
                and not member.is_symlink()
            ):
                continue
            raise DatasetContractError(
                f"uncontracted dataset runtime member: {member}"
            )


def _label_box_count(path: Path) -> int:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeError) as exc:
        raise DatasetContractError(f"cannot read dataset label {path}: {exc}") from exc
    for line in lines:
        fields = line.split()
        if len(fields) != 5 or fields[0] != "0":
            raise DatasetContractError(f"invalid one-class label line in {path}: {line!r}")
        try:
            coordinates = tuple(float(value) for value in fields[1:])
        except ValueError as exc:
            raise DatasetContractError(f"non-numeric label line in {path}: {line!r}") from exc
        if any(not 0.0 <= value <= 1.0 for value in coordinates) or any(
            value <= 0.0 for value in coordinates[2:]
        ):
            raise DatasetContractError(f"out-of-range label line in {path}: {line!r}")
    return len(lines)


def _canonical_hash(value: Any) -> str:
    payload = json.dumps(
        value, ensure_ascii=True, separators=(",", ":"), sort_keys=True
    ).encode("utf-8")
    return sha256(payload).hexdigest()


def verify_grouped_dataset_metadata(dataset_yaml: Path) -> None:
    """Require the generated YAML and runtime label map byte-for-byte.

    Exact text avoids ambiguous YAML duplicate-key behavior and binds the paths
    consumed by Ultralytics to the split directories covered by this contract.
    """

    data_file = dataset_yaml.expanduser().resolve()
    if data_file.name != "fort_cuh_grouped.yaml":
        raise DatasetContractError(
            "grouped dataset YAML must be named fort_cuh_grouped.yaml"
        )
    try:
        yaml_text = data_file.read_text(encoding="utf-8")
        labels_text = (data_file.parent / "labels.txt").read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        raise DatasetContractError(f"cannot read grouped dataset metadata: {exc}") from exc
    if yaml_text != GROUPED_DATASET_YAML:
        raise DatasetContractError(
            "grouped dataset YAML differs from the exact generated path contract"
        )
    if labels_text != GROUPED_LABELS:
        raise DatasetContractError(
            "grouped runtime labels must contain exactly 'player'"
        )


def build_dataset_contract(
    dataset_root: Path,
    *,
    splits: Sequence[str] = DEFAULT_SPLITS,
) -> dict[str, Any]:
    """Hash exact image/label members and validated one-class label contents."""

    root = dataset_root.expanduser().resolve()
    _reject_uncontracted_runtime_members(root)
    split_records: dict[str, Any] = {}
    for split in splits:
        images = _regular_files(root / "images" / split, IMAGE_SUFFIXES)
        labels = _regular_files(root / "labels" / split, frozenset({".txt"}))
        if not images:
            raise DatasetContractError(f"dataset image split is empty: {split}")
        expected_labels = {f"{Path(name).stem}.txt" for name in images}
        if len(expected_labels) != len(images):
            raise DatasetContractError(
                f"multiple images share a label stem in {split}"
            )
        actual_labels = set(labels)
        missing_labels = sorted(expected_labels.difference(actual_labels))
        extra_labels = sorted(actual_labels.difference(expected_labels))
        if missing_labels:
            raise DatasetContractError(
                f"missing label in {split}: {missing_labels[0]}"
            )
        if extra_labels:
            raise DatasetContractError(f"extra label in {split}: {extra_labels[0]}")
        members: list[dict[str, Any]] = []
        box_count = 0
        for image_name, image_path in images.items():
            label_name = f"{image_path.stem}.txt"
            label_path = labels[label_name]
            boxes = _label_box_count(label_path)
            box_count += boxes
            members.append(
                {
                    "image": image_name,
                    "image_sha256": _sha256_file(image_path),
                    "label": label_name,
                    "label_sha256": _sha256_file(label_path),
                    "boxes": boxes,
                }
            )
        split_record = {
            "images": len(members),
            "boxes": box_count,
            "members": members,
        }
        split_record["content_sha256"] = _canonical_hash(split_record)
        split_records[split] = split_record
    contract = {"schema_version": 1, "splits": split_records}
    contract["content_sha256"] = _canonical_hash(contract)
    return contract


def verify_dataset_contract(
    dataset_root: Path,
    expected: object,
    *,
    splits: Sequence[str] = DEFAULT_SPLITS,
) -> dict[str, Any]:
    """Recompute and compare an exact contract, reporting the first divergence."""

    if not isinstance(expected, Mapping) or expected.get("schema_version") != 1:
        raise DatasetContractError("dataset manifest has no supported exact-file contract")
    expected_splits = expected.get("splits")
    if not isinstance(expected_splits, Mapping) or set(expected_splits) != set(splits):
        raise DatasetContractError("dataset exact-file contract has invalid splits")
    root = dataset_root.expanduser().resolve()
    _reject_uncontracted_runtime_members(root)
    for split in splits:
        expected_split = expected_splits.get(split)
        if not isinstance(expected_split, Mapping) or not isinstance(
            expected_split.get("members"), list
        ):
            raise DatasetContractError(f"dataset contract split is invalid: {split}")
        expected_members = expected_split["members"]
        expected_images: dict[str, Mapping[str, Any]] = {}
        expected_labels: dict[str, Mapping[str, Any]] = {}
        for member in expected_members:
            if not isinstance(member, Mapping):
                raise DatasetContractError(f"dataset contract member is invalid: {split}")
            image_name = member.get("image")
            label_name = member.get("label")
            if not isinstance(image_name, str) or not isinstance(label_name, str):
                raise DatasetContractError(f"dataset contract member name is invalid: {split}")
            if image_name in expected_images or label_name in expected_labels:
                raise DatasetContractError(f"duplicate member in dataset contract: {split}")
            expected_images[image_name] = member
            expected_labels[label_name] = member
        actual_images = _regular_files(root / "images" / split, IMAGE_SUFFIXES)
        actual_labels = _regular_files(root / "labels" / split, frozenset({".txt"}))
        for description, expected_names, actual_names in (
            ("image", set(expected_images), set(actual_images)),
            ("label", set(expected_labels), set(actual_labels)),
        ):
            missing = sorted(expected_names.difference(actual_names))
            extra = sorted(actual_names.difference(expected_names))
            if missing:
                raise DatasetContractError(f"missing {description} in {split}: {missing[0]}")
            if extra:
                raise DatasetContractError(f"extra {description} in {split}: {extra[0]}")
        for name, member in expected_images.items():
            digest = _sha256_file(actual_images[name])
            if digest != member.get("image_sha256"):
                raise DatasetContractError(f"image hash mismatch in {split}: {name}")
        for name, member in expected_labels.items():
            _label_box_count(actual_labels[name])
            digest = _sha256_file(actual_labels[name])
            if digest != member.get("label_sha256"):
                raise DatasetContractError(f"label hash mismatch in {split}: {name}")
    actual = build_dataset_contract(root, splits=splits)
    if actual != expected:
        raise DatasetContractError("dataset exact-file contract aggregate mismatch")
    return actual
